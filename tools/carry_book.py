#!/usr/bin/env python3
# carry_book.py: the random fighters' carried book (the recipe spec, "one recipe per name", shared with VF1 and VF3
# Recomp: a seed name is the same fighter recipe in every game that has it) as a C++ source: every name of the game
# before's book with its recipe (leader, second, third, head, voice), for src/machine/random_book.inc. VF2's book is
# VF1's whole book, then VF2's own names with Lion or Shun (VF3 Recomp's tools/carry_book.py, the same).
#   carry_book.py --vf1 ../vf1-recomp/docs/SEEDS.md > src/machine/random_book.inc
#   carry_book.py --table book.txt > src/machine/random_book.inc   (lines "name leader second third head voice")
import sys

def from_vf1(path):
    # its tables' rows: | Seed | Head | Body | Arms | Legs | Moves (stance first) | Voice | (the featured ones twice)
    rows, seen = [], set()
    for line in open(path, encoding='utf-8'):
        if not line.startswith('|') or line.startswith('|---'):
            continue
        c = [x.strip() for x in line.strip().strip('|').split('|')]
        if len(c) < 7 or c[0] == 'Seed':
            continue
        name = c[0].strip('*').upper()
        three = [x.strip().upper() for x in c[5].split(',') if x.strip()]
        if name in seen:
            continue
        seen.add(name)
        while len(three) < 3:
            three.append('-')
        rows.append((name, three[0], three[1], three[2], c[1].upper(), c[6].upper()))
    return rows

def from_table(path):
    rows = []
    for line in open(path, encoding='utf-8'):
        f = line.split('#')[0].split()
        if len(f) == 6:
            rows.append(tuple(x.upper() for x in f))
    return rows

if len(sys.argv) != 3 or sys.argv[1] not in ('--vf1', '--table'):
    sys.exit('usage: carry_book.py --vf1 SEEDS.md | --table FILE')
rows = from_vf1(sys.argv[2]) if sys.argv[1] == '--vf1' else from_table(sys.argv[2])
src = 'VF1 Recomp docs/SEEDS.md' if sys.argv[1] == '--vf1' else sys.argv[2].split('/')[-1]
print('// The random fighters\' carried book: generated by tools/carry_book.py from %s (%d names; names and' % (src, len(rows)))
print('// character names only, as the published seed book). A line each: name leader second third head voice ("-": none)')
print('R"BOOK(')
for r in rows:
    print(' '.join(r))
print(')BOOK"')
